pub(super) fn statement_starts(dialect: SqlDialect) -> Vec<&'static str> {
    let own = match dialect {
        SqlDialect::Postgres => STARTS_POSTGRES,
        SqlDialect::MySql | SqlDialect::MariaDb => STARTS_MYSQL,
        SqlDialect::Sqlite => STARTS_SQLITE,
        SqlDialect::ClickHouse => STARTS_CLICKHOUSE,
        SqlDialect::SqlServer => STARTS_SQLSERVER,
        SqlDialect::Oracle => STARTS_ORACLE,
    };
    STARTS.iter().chain(own).copied().collect()
}

pub(super) fn general(dialect: SqlDialect) -> Vec<&'static str> {
    let own = match dialect {
        SqlDialect::Postgres => GENERAL_POSTGRES,
        SqlDialect::MySql | SqlDialect::MariaDb => GENERAL_MYSQL,
        SqlDialect::Sqlite => GENERAL_SQLITE,
        SqlDialect::ClickHouse => GENERAL_CLICKHOUSE,
        SqlDialect::SqlServer => GENERAL_SQLSERVER,
        SqlDialect::Oracle => GENERAL_ORACLE,
    };
    let mut words: Vec<&'static str> = GENERAL.iter().chain(own).copied().collect();
    words.dedup();
    words
}

