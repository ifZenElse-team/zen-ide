use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

use super::{Change, ObjectDiff, Part, SchemaDiff, find, plain_indexes, retarget};
use crate::dialect::SqlDialect;
use crate::schema::{Column, Constraint, ConstraintKind, Index, Object, ObjectKind, Policy, Schema, Trigger};

/// How to write a sync script.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "camelCase", default)]
pub struct ScriptOptions {
    /// Drop what only the target has (objects, columns, keys, indexes, triggers); otherwise each is left as a note.
    pub drop: bool,
}

/// Why a part of the difference is a note in the script instead of a statement.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "camelCase")]
pub enum NoteKind {
    /// Only the target has it and drops were not asked for.
    NotDropped,
    /// The dialect cannot change it in place (SQLite's columns and keys, ClickHouse's indexes).
    CannotAlter,
    /// It has to be changed by hand (a generated column's expression, a type's shape, partitioning).
    ByHand,
    /// No DDL could be generated for it (its details were not read).
    NoDdl,
}

/// A note of a sync script.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct Note {
    /// Why it is a note.
    pub kind: NoteKind,
    /// The object, qualified as the target's SQL writes it.
    pub object: String,
    /// The part of it, such as a column's name; empty for the object itself.
    pub part: String,
}

/// A sync script.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct SyncScript {
    /// The script: statements ending in `;`, notes as `--` comments.
    pub text: String,
    /// How many statements it has.
    pub statements: usize,
    /// What it could not write as statements.
    pub notes: Vec<Note>,
}

struct Out<'a> {
    dialect: SqlDialect,
    schema: String,
    text: String,
    statements: usize,
    notes: Vec<Note>,
    describe: &'a dyn Fn(&Note) -> String,
}

impl Out<'_> {
    fn statement(&mut self, text: impl AsRef<str>) {
        let text = text.as_ref().trim();
        if text.is_empty() {
            return;
        }
        self.text.push_str(text);
        if !text.ends_with(';') && !text.ends_with("DELIMITER ;") {
            self.text.push(';');
        }
        self.text.push('\n');
        self.statements += 1;
    }

    fn block(&mut self, text: &str) {
        let text = text.trim();
        if text.is_empty() {
            return;
        }
        self.text.push_str(text);
        self.text.push('\n');
        self.statements += text.matches(';').count().max(1);
    }

    fn note(&mut self, kind: NoteKind, object: &str, part: &str) {
        let note = Note { kind, object: object.to_owned(), part: part.to_owned() };
        let line = (self.describe)(&note);
        for line in line.lines() {
            self.text.push_str("-- ");
            self.text.push_str(line);
            self.text.push('\n');
        }
        self.notes.push(note);
    }

    fn table(&self, name: &str) -> String {
        self.dialect.qualified(&self.schema, name)
    }

    fn quote(&self, name: &str) -> String {
        self.dialect.quote(name)
    }

    fn mysql(&self) -> bool {
        matches!(self.dialect, SqlDialect::MySql | SqlDialect::MariaDb)
    }
}

pub fn column_definition(dialect: SqlDialect, column: &Column) -> String {
    let mut line = format!("{} {}", dialect.quote(&column.name), column.type_name);
    let not_null = |line: &mut String| {
        if !column.nullable {
            line.push_str(" NOT NULL");
        }
    };
    let default = |line: &mut String| {
        if let Some(default) = &column.default {
            line.push_str(&format!(" DEFAULT {default}"));
        }
    };
    match dialect {
        SqlDialect::Postgres => {
            if let Some(collation) = &column.collation {
                line.push_str(&format!(" COLLATE {collation}"));
            }
            match (column.identity.as_deref(), &column.generated) {
                (Some(identity), _) => line.push_str(if identity == "always" {
                    " GENERATED ALWAYS AS IDENTITY"
                } else {
                    " GENERATED BY DEFAULT AS IDENTITY"
                }),
                (None, Some(expression)) => line.push_str(&format!(" GENERATED ALWAYS AS ({expression}) STORED")),
                (None, None) => default(&mut line),
            }
            not_null(&mut line);
        }
        SqlDialect::MySql | SqlDialect::MariaDb => {
            if let Some(expression) = &column.generated {
                line.push_str(&format!(" GENERATED ALWAYS AS {expression}"));
            }
            if let Some(collation) = &column.collation {
                line.push_str(&format!(" COLLATE {collation}"));
            }
            not_null(&mut line);
            default(&mut line);
            if column.identity.is_some() {
                line.push_str(" AUTO_INCREMENT");
            }
            if let Some(comment) = &column.comment {
                line.push_str(&format!(" COMMENT {}", dialect.string(comment)));
            }
        }
        SqlDialect::Sqlite => {
            not_null(&mut line);
            default(&mut line);
        }
        SqlDialect::Oracle => {
            if column.identity.is_some() {
                line.push_str(" GENERATED BY DEFAULT AS IDENTITY");
            } else {
                default(&mut line);
            }
            not_null(&mut line);
        }
        SqlDialect::ClickHouse => {
            default(&mut line);
            if let Some(comment) = &column.comment {
                line.push_str(&format!(" COMMENT {}", dialect.string(comment)));
            }
        }
        SqlDialect::SqlServer => {
            if let Some(collation) = &column.collation {
                line.push_str(&format!(" COLLATE {collation}"));
            }
            if column.identity.is_some() {
                line.push_str(" IDENTITY(1,1)");
            }
            not_null(&mut line);
            default(&mut line);
        }
    }
    line
}

fn constraint_clause(dialect: SqlDialect, constraint: &Constraint) -> String {
    format!("CONSTRAINT {} {}", dialect.quote(&constraint.name), constraint.definition.trim().trim_end_matches(';'))
}

pub fn generic_create(dialect: SqlDialect, schema: &str, object: &Object) -> Option<String> {
    let name = dialect.qualified(schema, &object.name);
    match object.kind {
        ObjectKind::Table if !object.columns.is_empty() => {
            let mut lines: Vec<String> =
                object.columns.iter().map(|column| format!("    {}", column_definition(dialect, column))).collect();
            if dialect != SqlDialect::ClickHouse {
                for constraint in &object.constraints {
                    if constraint.kind != ConstraintKind::ForeignKey || dialect == SqlDialect::Sqlite {
                        lines.push(format!("    {}", constraint_clause(dialect, constraint)));
                    }
                }
            }
            let mut statement = format!("CREATE TABLE {name} (\n{}\n)", lines.join(",\n"));
            if dialect == SqlDialect::ClickHouse {
                statement.push_str(" ENGINE = MergeTree ORDER BY tuple()");
            }
            statement.push(';');
            Some(statement)
        }
        ObjectKind::View | ObjectKind::MaterializedView => {
            let query = object.definition.as_deref()?.trim().trim_end_matches(';');
            if query.to_ascii_lowercase().starts_with("create") {
                return Some(format!("{query};"));
            }
            let kind = if object.kind == ObjectKind::MaterializedView { "MATERIALIZED VIEW" } else { "VIEW" };
            Some(format!("CREATE {kind} {name} AS\n{query};"))
        }
        _ => None,
    }
}

fn drop_constraint(out: &Out<'_>, table: &str, constraint: &Constraint) -> Option<String> {
    let name = out.quote(&constraint.name);
    match out.dialect {
        SqlDialect::Sqlite => None,
        SqlDialect::MySql | SqlDialect::MariaDb => Some(match constraint.kind {
            ConstraintKind::PrimaryKey => format!("ALTER TABLE {table} DROP PRIMARY KEY"),
            ConstraintKind::ForeignKey => format!("ALTER TABLE {table} DROP FOREIGN KEY {name}"),
            ConstraintKind::Unique => format!("ALTER TABLE {table} DROP INDEX {name}"),
            ConstraintKind::Check | ConstraintKind::Exclusion => format!("ALTER TABLE {table} DROP CHECK {name}"),
        }),
        SqlDialect::Postgres | SqlDialect::ClickHouse | SqlDialect::SqlServer | SqlDialect::Oracle => {
            Some(format!("ALTER TABLE {table} DROP CONSTRAINT {name}"))
        }
    }
}

fn add_constraint(out: &Out<'_>, table: &str, constraint: &Constraint) -> Option<String> {
    match out.dialect {
        SqlDialect::Sqlite => None,
        SqlDialect::ClickHouse if constraint.kind != ConstraintKind::Check => None,
        _ => Some(format!("ALTER TABLE {table} ADD {}", constraint_clause(out.dialect, constraint))),
    }
}

fn drop_index(out: &Out<'_>, table: &str, index: &Index) -> Option<String> {
    match out.dialect {
        SqlDialect::Postgres | SqlDialect::Sqlite | SqlDialect::Oracle => {
            Some(format!("DROP INDEX {}", out.table(&index.name)))
        }
        SqlDialect::MySql | SqlDialect::MariaDb | SqlDialect::SqlServer => {
            Some(format!("DROP INDEX {} ON {table}", out.quote(&index.name)))
        }
        SqlDialect::ClickHouse => None,
    }
}

fn create_index(out: &Out<'_>, index: &Index) -> Option<String> {
    let definition = index.definition.trim();
    (out.dialect != SqlDialect::ClickHouse && !definition.is_empty()).then(|| definition.to_owned())
}

fn drop_trigger(out: &Out<'_>, table: &str, trigger: &Trigger) -> String {
    match out.dialect {
        SqlDialect::Postgres => format!("DROP TRIGGER {} ON {table}", out.quote(&trigger.name)),
        SqlDialect::MySql | SqlDialect::MariaDb => format!("DROP TRIGGER {}", out.table(&trigger.name)),
        SqlDialect::Sqlite | SqlDialect::ClickHouse | SqlDialect::SqlServer | SqlDialect::Oracle => {
            format!("DROP TRIGGER {}", out.quote(&trigger.name))
        }
    }
}

fn create_trigger(out: &mut Out<'_>, trigger: &Trigger) {
    let definition = trigger.definition.trim();
    if out.mysql() && definition.contains(';') {
        out.block(&format!("DELIMITER $$\n{}$$\nDELIMITER ;", definition.trim_end_matches(';')));
    } else {
        out.statement(definition);
    }
}

fn policy_statement(out: &Out<'_>, table: &str, policy: &Policy) -> String {
    let mut statement = format!(
        "CREATE POLICY {} ON {table} AS {} FOR {}",
        out.quote(&policy.name),
        if policy.permissive { "PERMISSIVE" } else { "RESTRICTIVE" },
        policy.command.to_ascii_uppercase()
    );
    if !policy.roles.is_empty() {
        statement.push_str(&format!(" TO {}", policy.roles.join(", ")));
    }
    if let Some(using) = &policy.using {
        statement.push_str(&format!(" USING ({using})"));
    }
    if let Some(check) = &policy.check {
        statement.push_str(&format!(" WITH CHECK ({check})"));
    }
    statement
}

fn kind_word(kind: ObjectKind) -> &'static str {
    match kind {
        ObjectKind::Table => "TABLE",
        ObjectKind::ForeignTable => "FOREIGN TABLE",
        ObjectKind::View => "VIEW",
        ObjectKind::MaterializedView => "MATERIALIZED VIEW",
        ObjectKind::Function => "FUNCTION",
        ObjectKind::Procedure => "PROCEDURE",
        ObjectKind::Sequence => "SEQUENCE",
        ObjectKind::Type => "TYPE",
        ObjectKind::Event => "EVENT",
        ObjectKind::Package => "PACKAGE",
    }
}

fn drop_object(out: &Out<'_>, object: &Object) -> String {
    let mut name = out.table(&object.name);
    if out.dialect == SqlDialect::Postgres
        && let Some(routine) = &object.routine
    {
        name.push_str(&format!("({})", routine.arguments));
    }
    if object.kind == ObjectKind::Type
        && out.dialect == SqlDialect::Postgres
        && object.type_info.as_ref().is_some_and(|info| info.kind == "domain")
    {
        return format!("DROP DOMAIN {name}");
    }
    format!("DROP {} {name}", kind_word(object.kind))
}

fn alter_column(out: &mut Out<'_>, table: &str, source: &Column, fields: &[String]) {
    let column = out.quote(&source.name);
    let has = |field: &str| fields.iter().any(|known| known == field);
    match out.dialect {
        SqlDialect::Sqlite => out.note(NoteKind::CannotAlter, table, &source.name),
        SqlDialect::Oracle => {
            if has("type") || has("nullable") || has("default") {
                let mut change = format!("{column} {}", source.type_name);
                if has("default") {
                    change.push_str(&format!(" DEFAULT {}", source.default.as_deref().unwrap_or("NULL")));
                }
                if has("nullable") {
                    change.push_str(if source.nullable { " NULL" } else { " NOT NULL" });
                }
                out.statement(format!("ALTER TABLE {table} MODIFY ({change})"));
            }
            if ["identity", "generated", "collation", "comment"].iter().any(|field| has(field)) {
                out.note(NoteKind::ByHand, table, &source.name);
            }
        }
        SqlDialect::SqlServer => {
            if has("type") || has("nullable") || has("collation") {
                let collation = source.collation.as_ref().map(|collation| format!(" COLLATE {collation}"));
                let null = if source.nullable { "NULL" } else { "NOT NULL" };
                out.statement(format!(
                    "ALTER TABLE {table} ALTER COLUMN {column} {}{} {null}",
                    source.type_name,
                    collation.unwrap_or_default()
                ));
            }
            if ["default", "identity", "generated", "comment"].iter().any(|field| has(field)) {
                out.note(NoteKind::ByHand, table, &source.name);
            }
        }
        SqlDialect::MySql | SqlDialect::MariaDb | SqlDialect::ClickHouse => {
            if has("generated") && out.dialect == SqlDialect::ClickHouse {
                out.note(NoteKind::ByHand, table, &source.name);
                return;
            }
            out.statement(format!("ALTER TABLE {table} MODIFY COLUMN {}", column_definition(out.dialect, source)));
        }
        SqlDialect::Postgres => {
            if has("type") || has("collation") {
                let collation = source.collation.as_ref().map(|collation| format!(" COLLATE {collation}"));
                out.statement(format!(
                    "ALTER TABLE {table} ALTER COLUMN {column} TYPE {}{}",
                    source.type_name,
                    collation.unwrap_or_default()
                ));
            }
            if has("default") {
                out.statement(match &source.default {
                    Some(default) => format!("ALTER TABLE {table} ALTER COLUMN {column} SET DEFAULT {default}"),
                    None => format!("ALTER TABLE {table} ALTER COLUMN {column} DROP DEFAULT"),
                });
            }
            if has("nullable") {
                let change = if source.nullable { "DROP" } else { "SET" };
                out.statement(format!("ALTER TABLE {table} ALTER COLUMN {column} {change} NOT NULL"));
            }
            if has("identity") {
                let how = |identity: &str| if identity == "always" { "ALWAYS" } else { "BY DEFAULT" };
                out.statement(match source.identity.as_deref() {
                    Some(identity) => {
                        format!("ALTER TABLE {table} ALTER COLUMN {column} ADD GENERATED {} AS IDENTITY", how(identity))
                    }
                    None => format!("ALTER TABLE {table} ALTER COLUMN {column} DROP IDENTITY IF EXISTS"),
                });
            }
            if has("generated") {
                out.note(NoteKind::ByHand, table, &source.name);
            }
            if has("comment") {
                let comment =
                    source.comment.as_deref().map_or_else(|| "NULL".to_owned(), |text| out.dialect.string(text));
                out.statement(format!("COMMENT ON COLUMN {table}.{column} IS {comment}"));
            }
        }
    }
}

fn identity_change(out: &mut Out<'_>, table: &str, source: &Column, target: &Column) -> bool {
    if out.dialect != SqlDialect::Postgres {
        return false;
    }
    match (source.identity.as_deref(), target.identity.as_deref()) {
        (Some(wanted), Some(had)) if wanted != had => {
            let how = if wanted == "always" { "ALWAYS" } else { "BY DEFAULT" };
            out.statement(format!("ALTER TABLE {table} ALTER COLUMN {} SET GENERATED {how}", out.quote(&source.name)));
            true
        }
        _ => false,
    }
}

struct Plan<'a> {
    diff: &'a SchemaDiff,
    source: &'a Schema,
    target: &'a Schema,
    create: &'a dyn Fn(&Schema, &Object) -> Option<String>,
    options: &'a ScriptOptions,
}

impl Plan<'_> {
    fn objects(&self, change: Change) -> impl Iterator<Item = &ObjectDiff> {
        self.diff.objects.iter().filter(move |object| object.change == change)
    }

    fn source_of(&self, object: &ObjectDiff) -> Option<&Object> {
        find(self.source, object.kind, &object.key)
    }

    fn target_of(&self, object: &ObjectDiff) -> Option<&Object> {
        find(self.target, object.kind, &object.key)
    }

    fn create_object(&self, out: &mut Out<'_>, object: &Object) {
        let mut copy = object.clone();
        if object.kind == ObjectKind::Table && out.dialect != SqlDialect::Sqlite {
            copy.constraints.retain(|constraint| constraint.kind != ConstraintKind::ForeignKey);
            if out.mysql() {
                copy.definition = None;
            }
        }
        let text = (self.create)(self.source, &copy).or_else(|| generic_create(out.dialect, &out.schema, &copy));
        match text {
            Some(text) if out.mysql() && text.contains("DELIMITER") => out.block(&text),
            Some(text) => {
                for statement in split_statements(&text) {
                    out.statement(statement);
                }
            }
            None => out.note(NoteKind::NoDdl, &out.table(&object.name), ""),
        }
    }
}

fn split_statements(text: &str) -> Vec<String> {
    if text.contains("$$") || text.contains("$function$") || text.to_ascii_uppercase().contains(" BEGIN") {
        return vec![text.trim().to_owned()];
    }
    text.split(";\n").map(|part| part.trim().to_owned()).filter(|part| !part.is_empty()).collect()
}

fn items(object: &ObjectDiff, part: Part, change: Change) -> impl Iterator<Item = &super::ItemDiff> {
    object.items.iter().filter(move |item| item.part == part && item.change == change)
}

const DROP_ORDER: [ObjectKind; 9] = [
    ObjectKind::Event,
    ObjectKind::View,
    ObjectKind::MaterializedView,
    ObjectKind::Function,
    ObjectKind::Procedure,
    ObjectKind::ForeignTable,
    ObjectKind::Table,
    ObjectKind::Sequence,
    ObjectKind::Type,
];

const CREATE_ORDER: [ObjectKind; 9] = [
    ObjectKind::Type,
    ObjectKind::Sequence,
    ObjectKind::Table,
    ObjectKind::ForeignTable,
    ObjectKind::Function,
    ObjectKind::Procedure,
    ObjectKind::View,
    ObjectKind::MaterializedView,
    ObjectKind::Event,
];

pub fn sync_script(
    diff: &SchemaDiff,
    (source, target): (&Schema, &Schema),
    dialect: SqlDialect,
    create: &dyn Fn(&Schema, &Object) -> Option<String>,
    describe: &dyn Fn(&Note) -> String,
    options: &ScriptOptions,
) -> SyncScript {
    let source = retarget(source, &target.name);
    let plan = Plan { diff, source: &source, target, create, options };
    let mut out =
        Out { dialect, schema: target.name.clone(), text: String::new(), statements: 0, notes: Vec::new(), describe };
    drop_parts(&plan, &mut out);
    drop_objects(&plan, &mut out);
    for kind in [ObjectKind::Type, ObjectKind::Sequence, ObjectKind::Table, ObjectKind::ForeignTable] {
        for object in plan.objects(Change::Added).filter(|object| object.kind == kind) {
            if let Some(found) = plan.source_of(object) {
                plan.create_object(&mut out, found);
            }
        }
    }
    change_columns(&plan, &mut out);
    change_definitions(&plan, &mut out);
    add_parts(&plan, &mut out);
    for kind in CREATE_ORDER.into_iter().filter(|kind| {
        !matches!(kind, ObjectKind::Type | ObjectKind::Sequence | ObjectKind::Table | ObjectKind::ForeignTable)
    }) {
        for object in plan.objects(Change::Added).filter(|object| object.kind == kind) {
            if let Some(found) = plan.source_of(object) {
                plan.create_object(&mut out, found);
            }
        }
    }
    add_foreign_keys(&plan, &mut out);
    properties(&plan, &mut out);
    let mut text = out.text;
    if out.statements > 0 && matches!(dialect, SqlDialect::MySql | SqlDialect::MariaDb | SqlDialect::ClickHouse) {
        text.insert_str(0, &format!("USE {};\n", dialect.quote(&target.name)));
        out.statements += 1;
    }
    SyncScript { text, statements: out.statements, notes: out.notes }
}

fn drop_parts(plan: &Plan<'_>, out: &mut Out<'_>) {
    let changed: Vec<&ObjectDiff> = plan.objects(Change::Changed).collect();
    for foreign in [true, false] {
        for object in &changed {
            let Some(target) = plan.target_of(object) else { continue };
            let table = out.table(&target.name);
            let wanted = if foreign { Part::ForeignKey } else { Part::Constraint };
            for item in object.items.iter().filter(|item| item.part == wanted && item.change != Change::Added) {
                if item.change == Change::Removed && !plan.options.drop {
                    out.note(NoteKind::NotDropped, &table, &item.name);
                    continue;
                }
                let Some(constraint) = target.constraints.iter().find(|constraint| constraint.name == item.name) else {
                    continue;
                };
                match drop_constraint(out, &table, constraint) {
                    Some(statement) => out.statement(statement),
                    None => out.note(NoteKind::CannotAlter, &table, &item.name),
                }
            }
        }
    }
    for object in &changed {
        let Some(target) = plan.target_of(object) else { continue };
        let table = out.table(&target.name);
        for item in object.items.iter().filter(|item| item.change != Change::Added) {
            let removed = item.change == Change::Removed;
            if !matches!(item.part, Part::Index | Part::Trigger | Part::Policy) {
                continue;
            }
            if removed && !plan.options.drop {
                out.note(NoteKind::NotDropped, &table, &item.name);
                continue;
            }
            let statement = match item.part {
                Part::Index => plain_indexes(target)
                    .into_iter()
                    .find(|index| index.name == item.name)
                    .and_then(|index| drop_index(out, &table, index)),
                Part::Trigger => target
                    .triggers
                    .iter()
                    .find(|trigger| trigger.name == item.name)
                    .map(|trigger| drop_trigger(out, &table, trigger)),
                _ => (out.dialect == SqlDialect::Postgres)
                    .then(|| format!("DROP POLICY {} ON {table}", out.quote(&item.name))),
            };
            match statement {
                Some(statement) => out.statement(statement),
                None => out.note(NoteKind::CannotAlter, &table, &item.name),
            }
        }
    }
}

fn drop_objects(plan: &Plan<'_>, out: &mut Out<'_>) {
    for kind in DROP_ORDER {
        for object in plan.objects(Change::Removed).filter(|object| object.kind == kind) {
            let Some(found) = plan.target_of(object) else { continue };
            if plan.options.drop {
                out.statement(drop_object(out, found));
            } else {
                out.note(NoteKind::NotDropped, &out.table(&found.name), "");
            }
        }
    }
}

fn change_columns(plan: &Plan<'_>, out: &mut Out<'_>) {
    for object in plan.objects(Change::Changed) {
        let (Some(source), Some(target)) = (plan.source_of(object), plan.target_of(object)) else { continue };
        if !matches!(object.kind, ObjectKind::Table | ObjectKind::ForeignTable) {
            continue;
        }
        let table = out.table(&target.name);
        for item in items(object, Part::Column, Change::Added) {
            if let Some(column) = source.columns.iter().find(|column| column.name == item.name) {
                out.statement(format!("ALTER TABLE {table} ADD COLUMN {}", column_definition(out.dialect, column)));
            }
        }
        for item in items(object, Part::Column, Change::Changed) {
            let Some(target_column) = target.columns.iter().find(|column| column.name == item.name) else { continue };
            let Some(column) = source
                .columns
                .iter()
                .find(|column| column.name == item.name)
                .or_else(|| source.columns.iter().find(|column| column.name.eq_ignore_ascii_case(&item.name)))
            else {
                continue;
            };
            let mut column = column.clone();
            column.name.clone_from(&target_column.name);
            let mut fields = item.fields.clone();
            if fields.iter().any(|field| field == "identity") && identity_change(out, &table, &column, target_column) {
                fields.retain(|field| field != "identity");
                if fields.is_empty() {
                    continue;
                }
            }
            alter_column(out, &table, &column, &fields);
        }
        for item in items(object, Part::Column, Change::Removed) {
            if !plan.options.drop {
                out.note(NoteKind::NotDropped, &table, &item.name);
            } else {
                out.statement(format!("ALTER TABLE {table} DROP COLUMN {}", out.quote(&item.name)));
            }
        }
    }
}

fn change_definitions(plan: &Plan<'_>, out: &mut Out<'_>) {
    for object in plan.objects(Change::Changed) {
        let (Some(source), Some(target)) = (plan.source_of(object), plan.target_of(object)) else { continue };
        if !object.items.iter().any(|item| item.part == Part::Definition) {
            continue;
        }
        let name = out.table(&target.name);
        match object.kind {
            ObjectKind::Sequence if out.dialect == SqlDialect::Postgres => {
                if let Some(sequence) = &source.sequence {
                    out.statement(format!(
                        "ALTER SEQUENCE {name} AS {} INCREMENT BY {} MINVALUE {} MAXVALUE {} CACHE {} {}CYCLE",
                        sequence.data_type,
                        sequence.increment,
                        sequence.min,
                        sequence.max,
                        sequence.cache,
                        if sequence.cycle { "" } else { "NO " }
                    ));
                }
            }
            ObjectKind::View if out.dialect == SqlDialect::Postgres => plan.create_object(out, source),
            ObjectKind::Function | ObjectKind::Procedure if out.dialect == SqlDialect::Postgres => {
                plan.create_object(out, source);
            }
            ObjectKind::View
            | ObjectKind::MaterializedView
            | ObjectKind::Function
            | ObjectKind::Procedure
            | ObjectKind::Event => {
                let mut statement = drop_object(out, target);
                if let Some(rest) = statement.strip_prefix("DROP ") {
                    let word = kind_word(target.kind);
                    statement = format!("DROP {word} IF EXISTS {}", rest.trim_start_matches(word).trim_start());
                }
                out.statement(statement);
                plan.create_object(out, source);
            }
            _ => out.note(NoteKind::ByHand, &name, ""),
        }
    }
}

fn add_parts(plan: &Plan<'_>, out: &mut Out<'_>) {
    for object in plan.objects(Change::Changed) {
        let (Some(source), Some(target)) = (plan.source_of(object), plan.target_of(object)) else { continue };
        let table = out.table(&target.name);
        for item in object.items.iter().filter(|item| item.change != Change::Removed) {
            match item.part {
                Part::Constraint => {
                    let Some(constraint) = source_constraint(source, item) else { continue };
                    match add_constraint(out, &table, constraint) {
                        Some(statement) => out.statement(statement),
                        None => out.note(NoteKind::CannotAlter, &table, &item.name),
                    }
                }
                Part::Index => {
                    let found = plain_indexes(source).into_iter().find(|index| index.name == item.name).or_else(|| {
                        let wanted = item.source.as_deref().unwrap_or_default();
                        plain_indexes(source).into_iter().find(|index| super::normal(&index.definition) == wanted)
                    });
                    match found.and_then(|index| create_index(out, index)) {
                        Some(statement) => out.statement(statement),
                        None => out.note(NoteKind::CannotAlter, &table, &item.name),
                    }
                }
                Part::Trigger => {
                    if let Some(trigger) = source.triggers.iter().find(|trigger| trigger.name == item.name) {
                        create_trigger(out, trigger);
                    }
                }
                Part::Policy => {
                    if let Some(policy) = source.policies.iter().find(|policy| policy.name == item.name) {
                        let statement = policy_statement(out, &table, policy);
                        out.statement(statement);
                    }
                }
                _ => {}
            }
        }
    }
}

fn source_constraint<'a>(source: &'a Object, item: &super::ItemDiff) -> Option<&'a Constraint> {
    source.constraints.iter().find(|constraint| constraint.name == item.name).or_else(|| {
        let wanted = item.source.as_deref().unwrap_or_default();
        source.constraints.iter().find(|constraint| super::normal(&constraint.definition) == wanted)
    })
}

fn add_foreign_keys(plan: &Plan<'_>, out: &mut Out<'_>) {
    if out.dialect == SqlDialect::Sqlite {
        for object in plan.objects(Change::Changed) {
            for item in
                object.items.iter().filter(|item| item.part == Part::ForeignKey && item.change != Change::Removed)
            {
                out.note(NoteKind::CannotAlter, &out.table(&object.name), &item.name);
            }
        }
        return;
    }
    for object in plan.objects(Change::Added).filter(|object| object.kind == ObjectKind::Table) {
        let Some(source) = plan.source_of(object) else { continue };
        let table = out.table(&source.name);
        for constraint in source.constraints.iter().filter(|constraint| constraint.kind == ConstraintKind::ForeignKey) {
            if let Some(statement) = add_constraint(out, &table, constraint) {
                out.statement(statement);
            }
        }
    }
    for object in plan.objects(Change::Changed) {
        let (Some(source), Some(target)) = (plan.source_of(object), plan.target_of(object)) else { continue };
        let table = out.table(&target.name);
        for item in object.items.iter().filter(|item| item.part == Part::ForeignKey && item.change != Change::Removed) {
            let Some(constraint) = source_constraint(source, item) else { continue };
            match add_constraint(out, &table, constraint) {
                Some(statement) => out.statement(statement),
                None => out.note(NoteKind::CannotAlter, &table, &item.name),
            }
        }
    }
}

fn properties(plan: &Plan<'_>, out: &mut Out<'_>) {
    for object in plan.objects(Change::Changed) {
        let (Some(source), Some(target)) = (plan.source_of(object), plan.target_of(object)) else { continue };
        let name = out.table(&target.name);
        for item in items(object, Part::Property, Change::Changed) {
            match item.name.as_str() {
                "comment" => {
                    let comment = source.comment.as_deref();
                    match out.dialect {
                        SqlDialect::Postgres => {
                            let text = comment.map_or_else(|| "NULL".to_owned(), |text| out.dialect.string(text));
                            let mut target_name = name.clone();
                            if let Some(routine) = &target.routine {
                                target_name.push_str(&format!("({})", routine.arguments));
                            }
                            out.statement(format!("COMMENT ON {} {target_name} IS {text}", kind_word(target.kind)));
                        }
                        SqlDialect::MySql | SqlDialect::MariaDb if target.kind == ObjectKind::Table => {
                            let text = out.dialect.string(comment.unwrap_or_default());
                            out.statement(format!("ALTER TABLE {name} COMMENT = {text}"));
                        }
                        _ => out.note(NoteKind::CannotAlter, &name, "comment"),
                    }
                }
                "rowSecurity" if out.dialect == SqlDialect::Postgres => {
                    let how = if source.row_security { "ENABLE" } else { "DISABLE" };
                    out.statement(format!("ALTER TABLE {name} {how} ROW LEVEL SECURITY"));
                }
                other => out.note(NoteKind::ByHand, &name, other),
            }
        }
    }
}
