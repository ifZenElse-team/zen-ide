use crate::driver::{DbError, ErrorKind};
use crate::schema::{Catalog, ConstraintKind, DdlOptions, Object, ObjectKind, Snapshot, find_object};

fn quote(name: &str) -> String {
    crate::schema::quote_for(super::ID, name)
}

fn qualified(schema: &str, name: &str) -> String {
    crate::schema::qualified_for(super::ID, schema, name)
}

fn literal(text: &str) -> String {
    format!("'{}'", text.replace('\'', "''"))
}

fn statement(text: &str) -> String {
    let trimmed = text.trim_end();
    let trimmed = trimmed.strip_suffix(';').unwrap_or(trimmed).trim_end();
    format!("{trimmed};")
}

fn privilege(letter: char) -> Option<&'static str> {
    Some(match letter {
        'r' => "SELECT",
        'a' => "INSERT",
        'w' => "UPDATE",
        'd' => "DELETE",
        'D' => "TRUNCATE",
        'x' => "REFERENCES",
        't' => "TRIGGER",
        'X' => "EXECUTE",
        'U' => "USAGE",
        'C' => "CREATE",
        'c' => "CONNECT",
        'T' => "TEMPORARY",
        'm' => "MAINTAIN",
        _ => return None,
    })
}

fn grants(object: &Object, target: &str) -> Vec<String> {
    let mut out = Vec::new();
    for item in &object.acl {
        let Some((grantee, rest)) = item.split_once('=') else { continue };
        let privileges = rest.split('/').next().unwrap_or_default();
        let grantee = if grantee.is_empty() { "PUBLIC".to_owned() } else { quote(grantee.trim_matches('"')) };
        if object.owner.as_deref().is_some_and(|owner| quote(owner) == grantee) {
            continue;
        }
        let mut plain = Vec::new();
        let mut with_grant = Vec::new();
        let mut letters = privileges.chars().peekable();
        while let Some(letter) = letters.next() {
            let grantable = letters.peek() == Some(&'*');
            if grantable {
                letters.next();
            }
            if let Some(name) = privilege(letter) {
                if grantable { with_grant.push(name) } else { plain.push(name) }
            }
        }
        if !plain.is_empty() {
            out.push(format!("GRANT {} ON {target} TO {grantee};", plain.join(", ")));
        }
        if !with_grant.is_empty() {
            out.push(format!("GRANT {} ON {target} TO {grantee} WITH GRANT OPTION;", with_grant.join(", ")));
        }
    }
    out
}

fn table(catalog: &Catalog, schema: &str, object: &Object, options: &DdlOptions) -> Vec<String> {
    let name = qualified(schema, &object.name);
    let mut out = Vec::new();
    let partition = object.partitioning.as_ref().filter(|partitioning| partitioning.parent.is_some());
    let foreign = object.kind == ObjectKind::ForeignTable;
    let mut after = Vec::new();
    if let Some(partition) = partition {
        out.push(format!(
            "CREATE TABLE {name} PARTITION OF {}\n    {};",
            partition.parent.clone().unwrap_or_default(),
            partition.bound.clone().unwrap_or_else(|| "DEFAULT".to_owned())
        ));
    } else {
        let mut lines: Vec<String> = object
            .columns
            .iter()
            .map(|column| {
                let mut line = format!("    {} {}", quote(&column.name), column.type_name);
                if let Some(collation) = &column.collation {
                    line.push_str(&format!(" COLLATE {collation}"));
                }
                match column.identity.as_deref() {
                    Some("always") => line.push_str(" GENERATED ALWAYS AS IDENTITY"),
                    Some(_) => line.push_str(" GENERATED BY DEFAULT AS IDENTITY"),
                    None => {}
                }
                if let Some(generated) = &column.generated {
                    line.push_str(&format!(" GENERATED ALWAYS AS ({generated}) STORED"));
                }
                if let Some(default) = &column.default {
                    line.push_str(&format!(" DEFAULT {default}"));
                }
                if !column.nullable {
                    line.push_str(" NOT NULL");
                }
                line
            })
            .collect();
        for constraint in &object.constraints {
            let separate = match constraint.kind {
                ConstraintKind::ForeignKey => options.separate_foreign_keys,
                ConstraintKind::PrimaryKey | ConstraintKind::Unique => options.separate_constraint_indexes,
                _ => false,
            };
            let clause = format!("CONSTRAINT {} {}", quote(&constraint.name), constraint.definition);
            if separate {
                after.push(format!("ALTER TABLE {name} ADD {clause};"));
            } else {
                lines.push(format!("    {clause}"));
            }
        }
        let mut create =
            format!("CREATE {}TABLE {name} (\n{}\n)", if foreign { "FOREIGN " } else { "" }, lines.join(",\n"));
        if let Some(key) = object.partitioning.as_ref().and_then(|partitioning| partitioning.key.as_ref()) {
            create.push_str(&format!("\nPARTITION BY {key}"));
        }
        if let Some(tablespace) = &object.tablespace {
            create.push_str(&format!("\nTABLESPACE {}", quote(tablespace)));
        }
        create.push(';');
        out.push(create);
    }
    out.extend(after);
    if options.nested {
        for index in object.indexes.iter().filter(|index| index.constraint.is_none()) {
            out.push(statement(&index.definition));
        }
        for trigger in &object.triggers {
            out.push(statement(&trigger.definition));
        }
        if object.row_security {
            out.push(format!("ALTER TABLE {name} ENABLE ROW LEVEL SECURITY;"));
        }
        for policy in &object.policies {
            let mut line = format!("CREATE POLICY {} ON {name}", quote(&policy.name));
            if !policy.permissive {
                line.push_str(" AS RESTRICTIVE");
            }
            if policy.command != "all" {
                line.push_str(&format!(" FOR {}", policy.command.to_uppercase()));
            }
            if !policy.roles.is_empty() && policy.roles != ["public"] {
                line.push_str(&format!(
                    " TO {}",
                    policy.roles.iter().map(|role| quote(role)).collect::<Vec<_>>().join(", ")
                ));
            }
            if let Some(using) = &policy.using {
                line.push_str(&format!(" USING ({using})"));
            }
            if let Some(check) = &policy.check {
                line.push_str(&format!(" WITH CHECK ({check})"));
            }
            line.push(';');
            out.push(line);
        }
    }
    if options.comments {
        if let Some(comment) = &object.comment {
            out.push(format!(
                "COMMENT ON {}TABLE {name} IS {};",
                if foreign { "FOREIGN " } else { "" },
                literal(comment)
            ));
        }
        for column in &object.columns {
            if let Some(comment) = &column.comment {
                out.push(format!("COMMENT ON COLUMN {name}.{} IS {};", quote(&column.name), literal(comment)));
            }
        }
    }
    if options.permissions {
        out.extend(grants(object, &format!("TABLE {name}")));
    }
    if options.partitions && object.partitioning.as_ref().is_some_and(|partitioning| partitioning.key.is_some()) {
        for other in &catalog.schemas {
            for child in &other.objects {
                if child.partitioning.as_ref().and_then(|partitioning| partitioning.parent.as_ref()) == Some(&name) {
                    out.push(String::new());
                    out.extend(table(catalog, &other.name, child, options));
                }
            }
        }
    }
    out
}

fn view(schema: &str, object: &Object, options: &DdlOptions) -> Vec<String> {
    let name = qualified(schema, &object.name);
    let query = object.definition.clone().unwrap_or_default();
    let query = query.trim_end().trim_end_matches(';').to_owned();
    let mut out = vec![if object.kind == ObjectKind::MaterializedView {
        format!("CREATE MATERIALIZED VIEW {name} AS\n{query}\nWITH DATA;")
    } else {
        format!("CREATE OR REPLACE VIEW {name} AS\n{query};")
    }];
    if options.nested {
        for index in &object.indexes {
            out.push(statement(&index.definition));
        }
        for trigger in &object.triggers {
            out.push(statement(&trigger.definition));
        }
    }
    let target = if object.kind == ObjectKind::MaterializedView { "MATERIALIZED VIEW" } else { "VIEW" };
    if options.comments {
        if let Some(comment) = &object.comment {
            out.push(format!("COMMENT ON {target} {name} IS {};", literal(comment)));
        }
        for column in &object.columns {
            if let Some(comment) = &column.comment {
                out.push(format!("COMMENT ON COLUMN {name}.{} IS {};", quote(&column.name), literal(comment)));
            }
        }
    }
    if options.permissions {
        out.extend(grants(object, &format!("TABLE {name}")));
    }
    out
}

fn routine(schema: &str, object: &Object, options: &DdlOptions) -> Result<Vec<String>, DbError> {
    let routine = object.routine.as_ref().ok_or_else(|| DbError::new(ErrorKind::Invalid, &object.name))?;
    let definition = routine
        .definition
        .clone()
        .ok_or_else(|| DbError::new(ErrorKind::Unsupported, format!("{}: no definition read", object.name)))?;
    let mut out = vec![statement(&definition)];
    let kind = if object.kind == ObjectKind::Procedure { "PROCEDURE" } else { "FUNCTION" };
    let target = format!("{kind} {}({})", qualified(schema, &object.name), routine.arguments);
    if options.comments
        && let Some(comment) = &object.comment
    {
        out.push(format!("COMMENT ON {target} IS {};", literal(comment)));
    }
    if options.permissions {
        out.extend(grants(object, &target));
    }
    Ok(out)
}

fn sequence(schema: &str, object: &Object, options: &DdlOptions) -> Vec<String> {
    let name = qualified(schema, &object.name);
    let mut out = Vec::new();
    if let Some(sequence) = &object.sequence {
        out.push(format!(
            "CREATE SEQUENCE {name}\n    AS {}\n    INCREMENT BY {}\n    MINVALUE {}\n    MAXVALUE {}\n    START {}\n    CACHE {}\n    {}CYCLE;",
            sequence.data_type,
            sequence.increment,
            sequence.min,
            sequence.max,
            sequence.start,
            sequence.cache,
            if sequence.cycle { "" } else { "NO " }
        ));
        if let Some(owner) = &sequence.owned_by {
            out.push(format!("ALTER SEQUENCE {name} OWNED BY {owner};"));
        }
    } else {
        out.push(format!("CREATE SEQUENCE {name};"));
    }
    if options.comments
        && let Some(comment) = &object.comment
    {
        out.push(format!("COMMENT ON SEQUENCE {name} IS {};", literal(comment)));
    }
    if options.permissions {
        out.extend(grants(object, &format!("SEQUENCE {name}")));
    }
    out
}

fn data_type(schema: &str, object: &Object, options: &DdlOptions) -> Vec<String> {
    let name = qualified(schema, &object.name);
    let info = object.type_info.clone().unwrap_or_default();
    let mut out = vec![match info.kind.as_str() {
        "enum" => format!(
            "CREATE TYPE {name} AS ENUM ({});",
            info.labels.iter().map(|label| literal(label)).collect::<Vec<_>>().join(", ")
        ),
        "domain" => {
            let mut line = format!("CREATE DOMAIN {name} AS {}", info.base.clone().unwrap_or_default());
            if let Some(default) = &info.default {
                line.push_str(&format!(" DEFAULT {default}"));
            }
            if info.not_null {
                line.push_str(" NOT NULL");
            }
            for check in &info.checks {
                line.push_str(&format!(" {check}"));
            }
            line.push(';');
            line
        }
        "range" => format!("CREATE TYPE {name} AS RANGE (SUBTYPE = {});", info.base.clone().unwrap_or_default()),
        _ => format!(
            "CREATE TYPE {name} AS (\n{}\n);",
            object
                .columns
                .iter()
                .map(|column| format!("    {} {}", quote(&column.name), column.type_name))
                .collect::<Vec<_>>()
                .join(",\n")
        ),
    }];
    if options.comments
        && let Some(comment) = &object.comment
    {
        let target = if info.kind == "domain" { "DOMAIN" } else { "TYPE" };
        out.push(format!("COMMENT ON {target} {name} IS {};", literal(comment)));
    }
    out
}

pub(super) fn generate(snapshot: &Snapshot, path: &[String], options: &DdlOptions) -> Result<String, DbError> {
    if let [catalog, schema] = path {
        let schema =
            snapshot.schema(catalog, schema).ok_or_else(|| DbError::new(ErrorKind::Invalid, path.join("/")))?;
        let name = quote(&schema.name);
        let mut parts = vec![match &schema.owner {
            Some(owner) => format!("CREATE SCHEMA {name} AUTHORIZATION {};", quote(owner)),
            None => format!("CREATE SCHEMA {name};"),
        }];
        if options.comments
            && let Some(comment) = &schema.comment
        {
            parts.push(format!("COMMENT ON SCHEMA {name} IS {};", literal(comment)));
        }
        return Ok(format!("{}\n", parts.join("\n")));
    }
    let found = find_object(snapshot, path).ok_or_else(|| DbError::new(ErrorKind::Invalid, path.join("/")))?;
    let (schema, object) = (found.schema.name.as_str(), found.object);
    if !object.detailed {
        return Err(DbError::new(ErrorKind::Unsupported, format!("{}: details not read yet", object.name)));
    }
    let name = qualified(schema, &object.name);
    let parts = match (found.sub, found.item) {
        (Some("indexes"), Some(item)) => {
            let index = object.indexes.iter().find(|index| index.name == item);
            vec![statement(&index.ok_or_else(|| DbError::new(ErrorKind::Invalid, item))?.definition)]
        }
        (Some("constraints" | "foreignKeys"), Some(item)) => {
            let constraint = object
                .constraints
                .iter()
                .find(|constraint| constraint.name == item)
                .ok_or_else(|| DbError::new(ErrorKind::Invalid, item))?;
            vec![format!("ALTER TABLE {name} ADD CONSTRAINT {} {};", quote(&constraint.name), constraint.definition)]
        }
        (Some("triggers"), Some(item)) => {
            let trigger = object.triggers.iter().find(|trigger| trigger.name == item);
            vec![statement(&trigger.ok_or_else(|| DbError::new(ErrorKind::Invalid, item))?.definition)]
        }
        (Some(_), Some(item)) => return Err(DbError::new(ErrorKind::Unsupported, item)),
        _ => match object.kind {
            ObjectKind::Table | ObjectKind::ForeignTable => table(found.catalog, schema, object, options),
            ObjectKind::View | ObjectKind::MaterializedView => view(schema, object, options),
            ObjectKind::Function | ObjectKind::Procedure => routine(schema, object, options)?,
            ObjectKind::Sequence => sequence(schema, object, options),
            ObjectKind::Type => data_type(schema, object, options),
            ObjectKind::Event => return Err(DbError::new(ErrorKind::Unsupported, "event")),
            ObjectKind::Package => return Err(DbError::new(ErrorKind::Unsupported, "package")),
        },
    };
    let mut text = parts.join("\n");
    text.push('\n');
    Ok(text)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::schema::{Catalog, Column, Constraint, Index, Level, Reference, Schema};

    fn snapshot() -> Snapshot {
        let mut orders = Object::new(ObjectKind::Table, "orders");
        orders.detailed = true;
        orders.owner = Some("ann".into());
        orders.comment = Some("Customer's orders".into());
        orders.acl = vec!["ann=arwdDxtm/ann".into(), "bob=r*w/ann".into()];
        orders.columns = vec![
            Column {
                name: "id".into(),
                position: 1,
                type_name: "bigint".into(),
                identity: Some("always".into()),
                ..Column::default()
            },
            Column {
                name: "customer".into(),
                position: 2,
                type_name: "integer".into(),
                nullable: true,
                comment: Some("who".into()),
                ..Column::default()
            },
        ];
        orders.constraints = vec![
            Constraint {
                name: "orders_pkey".into(),
                kind: ConstraintKind::PrimaryKey,
                columns: vec!["id".into()],
                definition: "PRIMARY KEY (id)".into(),
                references: None,
                index: Some("orders_pkey".into()),
                comment: None,
            },
            Constraint {
                name: "orders_customer_fkey".into(),
                kind: ConstraintKind::ForeignKey,
                columns: vec!["customer".into()],
                definition: "FOREIGN KEY (customer) REFERENCES customers(id)".into(),
                references: Some(Reference {
                    schema: "public".into(),
                    table: "customers".into(),
                    ..Reference::default()
                }),
                index: None,
                comment: None,
            },
        ];
        orders.indexes = vec![
            Index {
                name: "orders_pkey".into(),
                definition: "CREATE UNIQUE INDEX orders_pkey ON public.orders USING btree (id)".into(),
                constraint: Some("orders_pkey".into()),
                ..Index::default()
            },
            Index {
                name: "orders_customer".into(),
                definition: "CREATE INDEX orders_customer ON public.orders USING btree (customer)".into(),
                ..Index::default()
            },
        ];
        Snapshot {
            catalogs: vec![Catalog {
                name: "shop".into(),
                schemas_read: true,
                schemas: vec![Schema {
                    name: "public".into(),
                    level: Level::Details,
                    objects: vec![orders],
                    ..Schema::default()
                }],
                ..Catalog::default()
            }],
            ..Snapshot::new("pg", "postgresql")
        }
    }

    fn path(parts: &[&str]) -> Vec<String> {
        parts.iter().map(|part| (*part).to_owned()).collect()
    }

    #[test]
    fn a_table_alone_and_with_every_toggle() {
        let snapshot = snapshot();
        let table = path(&["shop", "public", "tables", "orders"]);
        let plain = generate(&snapshot, &table, &DdlOptions::default()).unwrap();
        assert_eq!(
            plain,
            "CREATE TABLE \"public\".\"orders\" (\n    \"id\" bigint GENERATED ALWAYS AS IDENTITY NOT NULL,\n    \"customer\" integer,\n    \
CONSTRAINT \"orders_pkey\" PRIMARY KEY (id),\n    CONSTRAINT \"orders_customer_fkey\" FOREIGN KEY (customer) REFERENCES customers(id)\n);\n"
        );
        let all = DdlOptions {
            nested: true,
            permissions: true,
            separate_foreign_keys: true,
            separate_constraint_indexes: true,
            comments: true,
            partitions: true,
        };
        let full = generate(&snapshot, &table, &all).unwrap();
        assert!(
            full.contains("ALTER TABLE \"public\".\"orders\" ADD CONSTRAINT \"orders_pkey\" PRIMARY KEY (id);"),
            "{full}"
        );
        assert!(full.contains("ADD CONSTRAINT \"orders_customer_fkey\" FOREIGN KEY"), "{full}");
        assert!(full.contains("CREATE INDEX orders_customer ON public.orders USING btree (customer);"), "{full}");
        assert!(!full.contains("CREATE UNIQUE INDEX orders_pkey"), "a key's index comes with its constraint: {full}");
        assert!(full.contains("COMMENT ON TABLE \"public\".\"orders\" IS 'Customer''s orders';"), "{full}");
        assert!(full.contains("COMMENT ON COLUMN \"public\".\"orders\".\"customer\" IS 'who';"), "{full}");
        assert!(full.contains("GRANT UPDATE ON TABLE \"public\".\"orders\" TO \"bob\";"), "{full}");
        assert!(full.contains("GRANT SELECT ON TABLE \"public\".\"orders\" TO \"bob\" WITH GRANT OPTION;"), "{full}");
        assert!(!full.contains("TO \"ann\""), "the owner's own privileges are implied: {full}");
        let index =
            generate(&snapshot, &path(&["shop", "public", "tables", "orders", "indexes", "orders_customer"]), &all);
        assert_eq!(index.unwrap(), "CREATE INDEX orders_customer ON public.orders USING btree (customer);\n");
    }

    #[test]
    fn a_schema_and_a_table_in_its_own_tablespace() {
        let mut snapshot = snapshot();
        let schema = &mut snapshot.catalogs[0].schemas[0];
        schema.owner = Some("ann".into());
        schema.comment = Some("The shop".into());
        schema.objects[0].tablespace = Some("fast".into());
        let created =
            generate(&snapshot, &path(&["shop", "public"]), &DdlOptions { comments: true, ..DdlOptions::default() });
        assert_eq!(
            created.unwrap(),
            "CREATE SCHEMA \"public\" AUTHORIZATION \"ann\";\nCOMMENT ON SCHEMA \"public\" IS 'The shop';\n"
        );
        let table =
            generate(&snapshot, &path(&["shop", "public", "tables", "orders"]), &DdlOptions::default()).unwrap();
        assert!(table.ends_with(")\nTABLESPACE \"fast\";\n"), "{table}");
    }
}
