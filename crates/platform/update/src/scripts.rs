use std::ffi::{OsStr, OsString};
use std::fs;
use std::io::{self, Read, Write};
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

pub const MARKER: &str = "Generated by Zen Toolbox. Do not edit.";

pub const PROFILE_COMMENT: &str = "# Zen IDE command-line launchers (added by Zen Toolbox)";

pub const COMPLETIONS_COMMENT: &str = "# Zen IDE shell completions (added by Zen Toolbox)";

pub const ZEN_CLI: &str = "zen";

const PROBE: u64 = 1024;

const LOGIN_SHELL_TIMEOUT: std::time::Duration = std::time::Duration::from_secs(5);

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Shell {
    Posix,
    Cmd,
}

impl Shell {
    pub fn current() -> Self {
        if cfg!(windows) { Self::Cmd } else { Self::Posix }
    }

    pub fn file_name(self, name: &str) -> String {
        match self {
            Self::Posix => name.to_owned(),
            Self::Cmd => format!("{name}.cmd"),
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CompletionShell {
    Zsh,
    Bash,
    Fish,
}

impl CompletionShell {
    pub const ALL: [Self; 3] = [Self::Zsh, Self::Bash, Self::Fish];

    pub fn name(self) -> &'static str {
        match self {
            Self::Zsh => "zsh",
            Self::Bash => "bash",
            Self::Fish => "fish",
        }
    }

    pub fn parse(name: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|shell| shell.name() == name)
    }

    pub fn script(self) -> &'static str {
        match self {
            Self::Zsh => include_str!("../completions/_zen"),
            Self::Bash => include_str!("../completions/zen.bash"),
            Self::Fish => include_str!("../completions/zen.fish"),
        }
    }

    pub fn file(self, home: &Path) -> PathBuf {
        match self {
            Self::Zsh => home.join(".local/share/zsh/site-functions/_zen"),
            Self::Bash => home.join(".local/share/bash-completion/completions/zen"),
            Self::Fish => home.join(".config/fish/completions/zen.fish"),
        }
    }

    pub fn in_use(self, home: &Path) -> bool {
        self != Self::Fish || home.join(".config/fish").is_dir()
    }
}

pub fn script(executable: &str, shell: Shell) -> String {
    match shell {
        Shell::Posix => format!("#!/bin/sh\n# {MARKER}\nexec {} \"$@\"\n", posix_quote(executable)),
        Shell::Cmd => format!("@echo off\r\nREM {MARKER}\r\n{} %*\r\n", cmd_quote(executable)),
    }
}

pub fn posix_quote(text: &str) -> String {
    let mut quoted = String::with_capacity(text.len() + 2);
    quoted.push('"');
    for character in text.chars() {
        if matches!(character, '"' | '\\' | '$' | '`') {
            quoted.push('\\');
        }
        quoted.push(character);
    }
    quoted.push('"');
    quoted
}

fn cmd_quote(text: &str) -> String {
    format!("\"{}\"", text.replace('"', "").replace('%', "%%"))
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Owner {
    Absent,
    Ours,
    Foreign,
}

pub fn owner(path: &Path) -> Owner {
    let metadata = match fs::symlink_metadata(path) {
        Ok(metadata) => metadata,
        Err(error) if error.kind() == io::ErrorKind::NotFound => return Owner::Absent,
        Err(_) => return Owner::Foreign,
    };
    if !metadata.is_file() {
        return Owner::Foreign;
    }
    let mut head = Vec::new();
    if fs::File::open(path).and_then(|file| file.take(PROBE).read_to_end(&mut head)).is_err() {
        return Owner::Foreign;
    }
    let marked = String::from_utf8_lossy(&head).lines().any(|line| {
        let line = line.trim_end_matches('\r');
        line.strip_prefix("# ").or_else(|| line.strip_prefix("REM ")) == Some(MARKER)
    });
    if marked { Owner::Ours } else { Owner::Foreign }
}

pub fn write(path: &Path, text: &str) -> io::Result<()> {
    let name = path.file_name().map(|name| name.to_string_lossy().into_owned()).unwrap_or_default();
    let staging = path.with_file_name(format!(".{name}.zen-partial"));
    let _ = fs::remove_file(&staging);
    let result = fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&staging)
        .and_then(|mut file| file.write_all(text.as_bytes()))
        .and_then(|()| mark_executable(&staging))
        .and_then(|()| fs::rename(&staging, path));
    if result.is_err() {
        let _ = fs::remove_file(&staging);
    }
    result
}

#[cfg(unix)]
fn mark_executable(path: &Path) -> io::Result<()> {
    use std::os::unix::fs::PermissionsExt;
    fs::set_permissions(path, fs::Permissions::from_mode(0o755))
}

#[cfg(not(unix))]
fn mark_executable(_: &Path) -> io::Result<()> {
    Ok(())
}

pub fn delete(path: &Path) -> io::Result<()> {
    match fs::remove_file(path) {
        Err(error) if error.kind() != io::ErrorKind::NotFound => Err(error),
        _ => Ok(()),
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Written {
    Written,
    Skipped,
}

pub fn write_launcher(dir: &Path, name: &str, executable: &Path, shell: Shell) -> io::Result<Written> {
    let path = dir.join(shell.file_name(name));
    if owner(&path) == Owner::Foreign {
        return Ok(Written::Skipped);
    }
    let executable = executable.to_str().ok_or_else(|| {
        io::Error::new(io::ErrorKind::InvalidInput, format!("{} is not valid Unicode", executable.display()))
    })?;
    fs::create_dir_all(dir)?;
    write(&path, &script(executable, shell))?;
    Ok(Written::Written)
}

pub fn on_path(dir: &Path, path: Option<&OsStr>) -> bool {
    let Some(path) = path else { return false };
    let canonical = fs::canonicalize(dir).ok();
    std::env::split_paths(path)
        .any(|entry| entry == dir || (canonical.is_some() && fs::canonicalize(&entry).ok() == canonical))
}

pub fn home() -> Option<PathBuf> {
    let env = |name: &str| std::env::var_os(name).filter(|value| !value.is_empty()).map(PathBuf::from);
    env("HOME").or_else(|| if cfg!(windows) { env("USERPROFILE") } else { None })
}

pub fn default_location() -> Option<PathBuf> {
    home().map(|home| home.join(".local").join("bin"))
}

pub fn expand_home(path: &Path) -> PathBuf {
    let mut components = path.components();
    match (components.next(), home()) {
        (Some(first), Some(home)) if first.as_os_str() == "~" => home.join(components.as_path()),
        _ => path.to_owned(),
    }
}

pub fn path_line(dir: &Path, home: Option<&Path>) -> String {
    let inside = home.and_then(|home| dir.strip_prefix(home).ok()).and_then(Path::to_str);
    let folder = match inside {
        Some("") => "$HOME".to_owned(),
        Some(relative) => format!("$HOME/{}", escape_in_quotes(relative)),
        None => escape_in_quotes(&dir.to_string_lossy()),
    };
    format!("export PATH=\"{folder}:$PATH\"")
}

fn escape_in_quotes(text: &str) -> String {
    let quoted = posix_quote(text);
    quoted[1..quoted.len() - 1].to_owned()
}

pub fn profiles(home: &Path) -> Vec<PathBuf> {
    let mut profiles = vec![home.join(".zprofile")];
    let bash = home.join(".bash_profile");
    if bash.exists() {
        profiles.push(bash);
    }
    profiles
}

fn has_line(profile: &Path, line: &str) -> bool {
    fs::read_to_string(profile).is_ok_and(|text| text.lines().any(|existing| existing.trim() == line))
}

pub fn in_profiles(dir: &Path, home: &Path) -> bool {
    let line = path_line(dir, Some(home));
    profiles(home).iter().any(|profile| has_line(profile, &line))
}

fn append_to_profile(profile: &Path, comment: &str, line: &str) -> io::Result<()> {
    let ends_with_newline = fs::read(profile).map_or(true, |bytes| bytes.is_empty() || bytes.ends_with(b"\n"));
    let mut file = fs::OpenOptions::new().create(true).append(true).open(profile)?;
    let separator = if ends_with_newline { "" } else { "\n" };
    file.write_all(format!("{separator}\n{comment}\n{line}\n").as_bytes())
}

pub fn add_to_profiles(dir: &Path, home: &Path) -> io::Result<Vec<PathBuf>> {
    let line = path_line(dir, Some(home));
    let mut changed = Vec::new();
    for profile in profiles(home) {
        if has_line(&profile, &line) {
            continue;
        }
        append_to_profile(&profile, PROFILE_COMMENT, &line)?;
        changed.push(profile);
    }
    Ok(changed)
}

pub fn completion_line(profile: &Path, home: &Path) -> String {
    let inside = |file: &Path| {
        let relative = file.strip_prefix(home).unwrap_or(file);
        format!("$HOME/{}", escape_in_quotes(&relative.to_string_lossy()))
    };
    if profile.file_name().is_some_and(|name| name == ".zprofile") {
        let functions = CompletionShell::Zsh.file(home);
        let folder = functions.parent().map_or_else(String::new, inside);
        format!("fpath=(\"{folder}\" $fpath)")
    } else {
        let file = inside(&CompletionShell::Bash.file(home));
        format!("[ -r \"{file}\" ] && . \"{file}\"")
    }
}

pub fn completions_in_profiles(home: &Path) -> bool {
    profiles(home).iter().all(|profile| has_line(profile, &completion_line(profile, home)))
}

pub fn add_completions_to_profiles(home: &Path) -> io::Result<Vec<PathBuf>> {
    let mut changed = Vec::new();
    for profile in profiles(home) {
        let line = completion_line(&profile, home);
        if has_line(&profile, &line) {
            continue;
        }
        append_to_profile(&profile, COMPLETIONS_COMMENT, &line)?;
        changed.push(profile);
    }
    Ok(changed)
}

pub fn login_shell_path(shell: &Path, home: &Path) -> Option<OsString> {
    const OPEN: &str = "<zen-path>";
    const CLOSE: &str = "</zen-path>";
    let mut child = std::process::Command::new(shell)
        .args(["-i", "-l", "-c", &format!("printf '\\n{OPEN}%s{CLOSE}\\n' \"$PATH\"")])
        .env("HOME", home)
        .env_remove("ZDOTDIR")
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::null())
        .spawn()
        .ok()?;
    let mut stdout = child.stdout.take()?;
    let (sender, receiver) = std::sync::mpsc::channel();
    std::thread::spawn(move || {
        let mut output = Vec::new();
        let _ = stdout.read_to_end(&mut output);
        let _ = sender.send(output);
    });
    let output = receiver.recv_timeout(LOGIN_SHELL_TIMEOUT);
    if output.is_err() {
        let _ = child.kill();
    }
    let _ = child.wait();
    let output = String::from_utf8_lossy(&output.ok()?).into_owned();
    let start = output.rfind(OPEN)? + OPEN.len();
    let end = start + output[start..].find(CLOSE)?;
    Some(OsString::from(&output[start..end]))
}

pub fn find_launcher(name: &str, path: &OsStr) -> Option<PathBuf> {
    let file = Shell::current().file_name(name);
    std::env::split_paths(path).map(|dir| dir.join(&file)).find(|candidate| owner(candidate) == Owner::Ours)
}

pub fn launcher_on_path(name: &str, home: Option<&Path>) -> Option<PathBuf> {
    std::env::var_os("PATH").and_then(|path| find_launcher(name, &path)).or_else(|| {
        let home = home?;
        let path = cfg!(unix).then(|| login_shell_path(&user_shell(), home)).flatten()?;
        find_launcher(name, &path)
    })
}

pub fn user_shell() -> PathBuf {
    std::env::var_os("SHELL")
        .filter(|shell| !shell.is_empty())
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from(if cfg!(target_os = "macos") { "/bin/zsh" } else { "/bin/sh" }))
}

#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct PathStatus {
    pub location: PathBuf,
    pub on_path: bool,
    pub in_profile: bool,
    pub line: String,
    pub profiles: Vec<PathBuf>,
    #[serde(default)]
    pub completions: bool,
}

pub fn path_status(dir: &Path, home: Option<&Path>) -> PathStatus {
    let new_window = || {
        let home = home?;
        cfg!(unix).then(|| login_shell_path(&user_shell(), home)).flatten()
    };
    let on_path =
        on_path(dir, std::env::var_os("PATH").as_deref()) || new_window().is_some_and(|path| on_path(dir, Some(&path)));
    PathStatus {
        location: dir.to_owned(),
        on_path,
        in_profile: home.is_some_and(|home| in_profiles(dir, home)),
        line: path_line(dir, home),
        profiles: home.map(profiles).unwrap_or_default(),
        completions: home.is_some_and(completions_in_profiles),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_completion_script_is_ours_and_calls_the_cli_for_its_candidates() {
        let dir = tempfile::tempdir().unwrap();
        for shell in CompletionShell::ALL {
            assert_eq!(CompletionShell::parse(shell.name()), Some(shell));
            assert!(shell.script().contains(&format!("__complete {}", shell.name())));
            let file = dir.path().join(shell.name());
            fs::write(&file, shell.script()).unwrap();
            assert_eq!(owner(&file), Owner::Ours, "{}", shell.name());
        }
        assert_eq!(CompletionShell::parse("powershell"), None);
    }

    #[test]
    fn fish_gets_a_file_only_when_fish_is_set_up() {
        let dir = tempfile::tempdir().unwrap();
        assert!(CompletionShell::Zsh.in_use(dir.path()));
        assert!(CompletionShell::Bash.in_use(dir.path()));
        assert!(!CompletionShell::Fish.in_use(dir.path()));
        fs::create_dir_all(dir.path().join(".config/fish")).unwrap();
        assert!(CompletionShell::Fish.in_use(dir.path()));
    }

    #[test]
    fn completion_lines_go_once_into_each_profile() {
        let dir = tempfile::tempdir().unwrap();
        let home = dir.path();
        fs::write(home.join(".bash_profile"), "export A=1").unwrap();
        assert!(!completions_in_profiles(home));
        assert_eq!(add_completions_to_profiles(home).unwrap(), [home.join(".zprofile"), home.join(".bash_profile")]);
        assert!(completions_in_profiles(home));
        assert!(add_completions_to_profiles(home).unwrap().is_empty(), "the lines are there already");
        let zsh = fs::read_to_string(home.join(".zprofile")).unwrap();
        assert!(zsh.contains("fpath=(\"$HOME/.local/share/zsh/site-functions\" $fpath)"), "{zsh}");
        let bash = fs::read_to_string(home.join(".bash_profile")).unwrap();
        assert!(bash.starts_with("export A=1\n\n# Zen IDE shell completions"), "{bash}");
        assert!(bash.contains(". \"$HOME/.local/share/bash-completion/completions/zen\""), "{bash}");
    }

    #[test]
    fn a_posix_launcher_passes_every_argument_on() {
        assert_eq!(
            script("/Applications/GoGarden.app/Contents/MacOS/gogarden", Shell::Posix),
            "#!/bin/sh\n# Generated by Zen Toolbox. Do not edit.\nexec \"/Applications/GoGarden.app/Contents/MacOS/gogarden\" \"$@\"\n"
        );
    }

    #[test]
    fn the_path_line_names_the_home_folder_by_variable() {
        let home = Path::new("/Users/me");
        assert_eq!(path_line(&home.join(".local/bin"), Some(home)), r#"export PATH="$HOME/.local/bin:$PATH""#);
        assert_eq!(path_line(Path::new("/opt/zen bin"), Some(home)), r#"export PATH="/opt/zen bin:$PATH""#);
        assert_eq!(path_line(Path::new("/opt/$x"), None), r#"export PATH="/opt/\$x:$PATH""#);
    }

    #[test]
    fn the_path_line_is_added_once_to_zprofile_and_an_existing_bash_profile() {
        let home = tempfile::tempdir().unwrap();
        let home = home.path();
        let bin = home.join(".local/bin");
        assert_eq!(profiles(home), [home.join(".zprofile")], "no .bash_profile: zsh only");
        assert!(!in_profiles(&bin, home));

        fs::write(home.join(".bash_profile"), "export EDITOR=vi").unwrap();
        let changed = add_to_profiles(&bin, home).unwrap();
        assert_eq!(changed, [home.join(".zprofile"), home.join(".bash_profile")]);
        assert_eq!(
            fs::read_to_string(home.join(".zprofile")).unwrap(),
            format!("\n{PROFILE_COMMENT}\nexport PATH=\"$HOME/.local/bin:$PATH\"\n")
        );
        assert_eq!(
            fs::read_to_string(home.join(".bash_profile")).unwrap(),
            format!("export EDITOR=vi\n\n{PROFILE_COMMENT}\nexport PATH=\"$HOME/.local/bin:$PATH\"\n"),
            "the user's lines stay as they were"
        );
        assert!(in_profiles(&bin, home));
        assert!(add_to_profiles(&bin, home).unwrap().is_empty(), "never twice");
    }

    #[cfg(unix)]
    #[test]
    fn a_new_terminal_window_sees_the_line() {
        let home = tempfile::tempdir().unwrap();
        let home = home.path();
        let bin = home.join(".local/bin");
        fs::create_dir_all(&bin).unwrap();
        for shell in ["/bin/zsh", "/bin/bash"] {
            if !Path::new(shell).exists() {
                continue;
            }
            let path = login_shell_path(Path::new(shell), home);
            assert!(path.is_some(), "{shell} says its PATH");
            assert!(!on_path(&bin, path.as_deref()), "{shell}: not before the line is added");
        }
        fs::write(home.join(".bash_profile"), "").unwrap();
        add_to_profiles(&bin, home).unwrap();
        for shell in ["/bin/zsh", "/bin/bash"] {
            if Path::new(shell).exists() {
                let path = login_shell_path(Path::new(shell), home);
                assert!(on_path(&bin, path.as_deref()), "{shell}: {path:?}");
            }
        }
    }

    #[cfg(unix)]
    #[test]
    fn a_launcher_runs_from_any_folder_with_every_argument() {
        let dir = tempfile::tempdir().unwrap();
        let program = dir.path().join("my ide");
        fs::write(&program, "#!/bin/sh\nprintf '%s|' \"$PWD\" \"$@\"\n").unwrap();
        mark_executable(&program).unwrap();
        let bin = dir.path().join("bin");
        assert_eq!(write_launcher(&bin, "gogarden", &program, Shell::Posix).unwrap(), Written::Written);
        let elsewhere = tempfile::tempdir().unwrap();
        let output = std::process::Command::new(bin.join("gogarden"))
            .args(["--headless", ".", "main.go:12", "two words"])
            .current_dir(elsewhere.path())
            .output()
            .unwrap();
        let pwd = fs::canonicalize(elsewhere.path()).unwrap();
        let printed = String::from_utf8(output.stdout).unwrap();
        let printed = printed.replace("/private/var/", "/var/");
        let expected =
            format!("{}|--headless|.|main.go:12|two words|", pwd.display()).replace("/private/var/", "/var/");
        assert_eq!(printed, expected);
    }

    #[test]
    fn only_a_launcher_zen_wrote_counts_as_found() {
        let dir = tempfile::tempdir().unwrap();
        let (mine, other, ours) = (dir.path().join("mine"), dir.path().join("other"), dir.path().join("ours"));
        for folder in [&mine, &other, &ours] {
            fs::create_dir_all(folder).unwrap();
        }
        let shell = Shell::current();
        fs::write(mine.join(shell.file_name("gogarden")), "#!/bin/sh\necho mine\n").unwrap();
        write_launcher(&ours, "gogarden", Path::new("/Applications/GoGarden.app/Contents/MacOS/gogarden"), shell)
            .unwrap();
        let path = std::env::join_paths([&mine, &other, &ours]).unwrap();
        assert_eq!(find_launcher("gogarden", &path), Some(ours.join(shell.file_name("gogarden"))));
        assert_eq!(find_launcher("rustronin", &path), None);
        let without = std::env::join_paths([&mine, &other]).unwrap();
        assert_eq!(find_launcher("gogarden", &without), None, "someone else's gogarden is not ours");
    }

    #[test]
    fn a_file_of_someone_else_is_never_replaced() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("gogarden");
        fs::write(&path, "#!/bin/sh\necho mine\n").unwrap();
        assert_eq!(write_launcher(dir.path(), "gogarden", Path::new("/x"), Shell::Posix).unwrap(), Written::Skipped);
        assert_eq!(fs::read_to_string(&path).unwrap(), "#!/bin/sh\necho mine\n");
        assert_eq!(owner(&path), Owner::Foreign);
        assert_eq!(owner(&dir.path().join("missing")), Owner::Absent);
    }
}
